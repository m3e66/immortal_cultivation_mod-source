/** Reads the shipped loot data, rather than maintaining a second list of drops and chances.
 * The resource index is regenerated by processResources, including when content is excluded
 * from a release. Loot modifiers are expanded onto their actual source tables.
 */
public final class AcquisitionCatalog {
    private static final String MOD = ImmortalCultivationMod.MODID;
    private AcquisitionCatalog() {}

    public static List<AcquisitionRecipe> collect() {
        Map<ResourceLocation, JsonObject> tables = new LinkedHashMap<>();
        List<JsonObject> modifiers = new ArrayList<>();
        try (var reader = reader("assets/" + MOD + "/jei/loot_index.txt")) {
            for (String path : reader.lines().toList()) {
                try (var json = reader(path)) {
                    JsonObject data = JsonParser.parseReader(json).getAsJsonObject();
                    if (path.contains("/loot_table/")) {
                        String[] parts = path.split("/loot_table/", 2);
                        String namespace = parts[0].substring("data/".length());
                        tables.put(ResourceLocation.fromNamespaceAndPath(namespace,
                                parts[1].substring(0, parts[1].length() - 5)), data);
                    } else if ("neoforge:add_table".equals(string(data, "type", ""))) modifiers.add(data);
                }
            }
        } catch (IOException | RuntimeException e) {
            LogUtils.getLogger().error("Unable to read JEI acquisition loot catalog", e);
        }
        List<AcquisitionRecipe> result = new ArrayList<>();
        for (var entry : tables.entrySet()) appendTable(result, entry.getKey(), entry.getKey(), entry.getValue());
        for (JsonObject modifier : modifiers) {
            JsonObject bonus = tables.get(ResourceLocation.parse(modifier.get("table").getAsString()));
            if (bonus == null) continue;
            for (ResourceLocation source : modifierSources(modifier)) {
                appendTable(result, source, ResourceLocation.parse(modifier.get("table").getAsString()), bonus);
            }
        }
        result.addAll(flames());
        expandBeastRealms(result);
        result.sort(Comparator.comparing(recipe -> recipe.id().toString()));
        return List.copyOf(result);
    }

    private static void expandBeastRealms(List<AcquisitionRecipe> recipes) {
        for (var recipe : List.copyOf(recipes)) {
            if (recipe.kind() != AcquisitionRecipe.Kind.MOB) continue;
            if (recipe.id().getPath().startsWith("acquisition/" + MOD + "/entities/escaped_yuanying_core/")) {
                recipes.remove(recipe);
                var dragon = com.example.immortal_cultivation_mod.entity.ModEntities.CRIMSON_SKY_FLAME_FLOOD_DRAGON.get();
                for (int realm : com.example.immortal_cultivation_mod.entity.BeastRealms.variants(dragon)) {
                    var icon = new ItemStack(SpawnEggItem.byId(dragon));
                    com.example.immortal_cultivation_mod.item.BeastSpawnEggItem.selectRealm(icon, realm);
                    var notes = new ArrayList<>(recipe.details());
                    notes.add(text("escaped_core"));
                    recipes.add(new AcquisitionRecipe(recipe.id().withPath(recipe.id().getPath() + "/realm_" + realm),
                            recipe.kind(), com.example.immortal_cultivation_mod.entity.BeastRealms.prefix(realm, recipe.sourceName()),
                            icon, com.example.immortal_cultivation_mod.entity.BeastRealmEvents.realmDrop(recipe.result(), realm),
                            notes, List.of(new ItemStack(Items.GLASS_BOTTLE), new ItemStack(
                                    com.example.immortal_cultivation_mod.magicritual.item.ModItems.SPIRIT_STORAGE_CRYSTAL.get()))));
                }
                continue;
            }
            if (!(recipe.sourceIcon().getItem() instanceof com.example.immortal_cultivation_mod.item.BeastSpawnEggItem egg)) continue;
            recipes.remove(recipe);
            for (int realm : com.example.immortal_cultivation_mod.entity.BeastRealms.variants(egg.getType(recipe.sourceIcon()))) {
                // The former Golden Core guardian's boss bonus remains exclusive to that variant.
                if (egg.getType(recipe.sourceIcon()) == com.example.immortal_cultivation_mod.entity.ModEntities.VAULT_GUARDIAN.get()
                        && realm < 3 && recipe.id().getPath().contains("/entities/weapon_care_boss_bonus/")) continue;
                // Every dragon variant yields its rewards through the escaped spirit.
                if (egg.getType(recipe.sourceIcon()) == com.example.immortal_cultivation_mod.entity.ModEntities.CRIMSON_SKY_FLAME_FLOOD_DRAGON.get()) continue;
                var drop = com.example.immortal_cultivation_mod.entity.BeastRealmEvents.realmDrop(recipe.result(), realm);
                if (drop.isEmpty()) continue;
                var icon = recipe.sourceIcon().copy();
                com.example.immortal_cultivation_mod.item.BeastSpawnEggItem.selectRealm(icon, realm);
                recipes.add(new AcquisitionRecipe(recipe.id().withPath(recipe.id().getPath() + "/realm_" + realm),
                        recipe.kind(), com.example.immortal_cultivation_mod.entity.BeastRealms.prefix(realm, recipe.sourceName()),
                        icon, drop, recipe.details(), recipe.relatedItems()));
            }
        }
    }

    private static BufferedReader reader(String path) throws IOException {
        var stream = AcquisitionCatalog.class.getClassLoader().getResourceAsStream(path);
        if (stream == null) throw new IOException("Missing acquisition resource " + path);
        return new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
    }

    public static List<ResourceLocation> modifierSources(JsonObject modifier) {
        List<ResourceLocation> sources = new ArrayList<>();
        findTableIds(modifier.get("conditions"), sources);
        return sources.stream().distinct().toList();
    }

    private static void findTableIds(JsonElement element, List<ResourceLocation> sources) {
        if (element == null) return;
        if (element.isJsonArray()) element.getAsJsonArray().forEach(value -> findTableIds(value, sources));
        else if (element.isJsonObject()) {
            JsonObject object = element.getAsJsonObject();
            if ("neoforge:loot_table_id".equals(string(object, "condition", ""))) {
                sources.add(ResourceLocation.parse(object.get("loot_table_id").getAsString()));
            } else if (object.has("terms")) findTableIds(object.get("terms"), sources);
        }
    }

    public static void appendTable(List<AcquisitionRecipe> out, ResourceLocation sourceTable,
                                   ResourceLocation dataTable, JsonObject table) {
        String path = sourceTable.getPath();
        int slash = path.indexOf('/');
        if (slash < 0) return;
        ResourceLocation sourceId = ResourceLocation.fromNamespaceAndPath(sourceTable.getNamespace(), path.substring(slash + 1));
        AcquisitionRecipe.Kind kind;
        Component name;
        ItemStack icon;
        if (path.startsWith("entities/")) {
            if (!BuiltInRegistries.ENTITY_TYPE.containsKey(sourceId)) return; // Bonus tables are not monsters.
            var entity = BuiltInRegistries.ENTITY_TYPE.get(sourceId);
            name = entity.getDescription();
            SpawnEggItem egg = SpawnEggItem.byId(entity);
            icon = new ItemStack(egg == null ? Items.ROTTEN_FLESH : egg);
            kind = AcquisitionRecipe.Kind.MOB;
        } else if (path.startsWith("blocks/")) {
            if (!BuiltInRegistries.BLOCK.containsKey(sourceId)) return;
            var block = BuiltInRegistries.BLOCK.get(sourceId);
            name = block.getName();
            icon = new ItemStack(block.asItem() == Items.AIR ? Items.IRON_PICKAXE : block.asItem());
            kind = AcquisitionRecipe.Kind.BLOCK;
        } else if (path.startsWith("chests/") && !path.endsWith("_bonus")) {
            name = text("chest_source", Component.translatableWithFallback(
                    "jei." + MOD + ".source." + sourceId.getPath().replace('/', '.'), humanName(sourceId.getPath())));
            icon = new ItemStack(Items.CHEST);
            kind = AcquisitionRecipe.Kind.CHEST;
        } else return;
        int poolIndex = 0;
        for (JsonElement element : array(table, "pools")) {
            JsonObject pool = element.getAsJsonObject();
            List<Component> notes = new ArrayList<>();
            notes.add(text("rolls", number(pool.get("rolls"), "1")));
            notes.addAll(conditions(pool.get("conditions")));
            JsonArray entries = array(pool, "entries");
            int totalWeight = 0;
            for (JsonElement entry : entries) totalWeight += weight(entry.getAsJsonObject());
            int entryIndex = 0;
            for (JsonElement entry : entries) {
                List<Component> entryNotes = new ArrayList<>(notes);
                if (entries.size() > 1) entryNotes.add(text("weight", weight(entry.getAsJsonObject()), totalWeight));
                visit(out, sourceTable, dataTable, kind, name, icon, entry.getAsJsonObject(), entryNotes,
                        "p" + poolIndex + "_e" + entryIndex++);
            }
            poolIndex++;
        }
    }

    private static void visit(List<AcquisitionRecipe> out, ResourceLocation source, ResourceLocation data,
                              AcquisitionRecipe.Kind kind, Component name, ItemStack icon, JsonObject entry,
                              List<Component> inherited, String branch) {
        List<Component> notes = new ArrayList<>(inherited);
        notes.addAll(conditions(entry.get("conditions")));
        String type = string(entry, "type", "");
        if ("minecraft:alternatives".equals(type) || "minecraft:group".equals(type) || "minecraft:sequence".equals(type)) {
            List<Component> previousFailures = new ArrayList<>();
            int index = 0;
            for (JsonElement child : array(entry, "children")) {
                var childNotes = new ArrayList<>(notes);
                childNotes.addAll(previousFailures);
                visit(out, source, data, kind, name, icon, child.getAsJsonObject(), childNotes, branch + "_c" + index++);
                if ("minecraft:alternatives".equals(type)) {
                    var conditionNotes = conditions(child.getAsJsonObject().get("conditions"));
                    if (conditionNotes.isEmpty()) break; // An unconditional alternative prevents later entries.
                    previousFailures.add(text("not", join(conditionNotes, "; ")));
                }
            }
            return;
        }
        if (!"minecraft:item".equals(type)) return;
        ResourceLocation itemId = ResourceLocation.tryParse(string(entry, "name", ""));
        if (itemId == null || !BuiltInRegistries.ITEM.containsKey(itemId)) return;
        Item item = BuiltInRegistries.ITEM.get(itemId);
        if (item == Items.AIR) return;
        String count = "1";
        for (JsonElement element : array(entry, "functions")) {
            JsonObject function = element.getAsJsonObject();
            switch (string(function, "function", "")) {
                case "minecraft:set_count" -> count = number(function.get("count"), "1");
                case "minecraft:apply_bonus" -> notes.add(text("fortune_bonus"));
                case "minecraft:explosion_decay" -> notes.add(text("explosion_decay"));
                default -> notes.add(text("function", string(function, "function", "")));
            }
        }
        // Picking up an ordinary placed block is not an acquisition recipe. Keep meaningful
        // tool requirements, chances, extra quantities, and modifier-provided bonus drops.
        if (kind == AcquisitionRecipe.Kind.BLOCK && source.equals(data)
                && icon.getItem() instanceof net.minecraft.world.item.BlockItem && icon.is(item)
                && "1".equals(count) && notes.stream().allMatch(note -> note.equals(text("rolls", "1"))
                    || note.equals(text("survives_explosion")) || note.equals(text("explosion_decay")))) return;
        notes.addFirst(text("count", count));
        notes.add(text("shipped_loot"));
        notes.add(text("loot_table", data.toString()));
        ResourceLocation id = ResourceLocation.fromNamespaceAndPath(MOD,
                "acquisition/" + source.getNamespace() + "/" + source.getPath() + "/"
                        + data.getNamespace() + "/" + data.getPath() + "/" + branch);
        out.add(new AcquisitionRecipe(id, kind, name, icon, new ItemStack(item), notes, List.of()));
    }

    public static List<Component> conditions(JsonElement element) {
        List<Component> notes = new ArrayList<>();
        if (element == null) return notes;
        if (element.isJsonArray()) element.getAsJsonArray().forEach(value -> notes.addAll(conditions(value)));
        else if (element.isJsonObject()) {
            JsonObject condition = element.getAsJsonObject();
            String id = string(condition, "condition", "");
            switch (id) {
                case "minecraft:survives_explosion" -> notes.add(text("survives_explosion"));
                case "minecraft:random_chance" -> notes.add(text("chance", percent(condition.get("chance").getAsDouble())));
                case MOD + ":fortune_chance" -> notes.add(text("fortune_chance", percent(condition.get("chance").getAsDouble())));
                case "minecraft:inverted" -> notes.add(text("not", join(conditions(condition.get("term")), "; ")));
                case "minecraft:any_of", "minecraft:all_of" -> notes.add(join(conditions(condition.get("terms")),
                        id.equals("minecraft:any_of") ? " / " : "; "));
                case "minecraft:match_tool" -> {
                    String predicate = condition.get("predicate").toString();
                    boolean shears = predicate.contains("minecraft:shears");
                    boolean silk = predicate.contains("minecraft:silk_touch");
                    notes.add(text(shears && silk ? "shears_or_silk" : shears ? "shears" : silk ? "silk" : "tool_condition"));
                }
                case "minecraft:block_state_property" -> notes.add(text("block_state", condition.get("properties").toString()));
                case "minecraft:table_bonus" -> notes.add(text("enchantment_chance", string(condition, "enchantment", ""),
                        joinPercents(array(condition, "chances"))));
                case "minecraft:entity_properties" -> notes.add(text("entity_condition", condition.get("predicate").toString()));
                case "minecraft:killed_by_player" -> notes.add(text("player_kill"));
                default -> notes.add(text("condition", id));
            }
        }
        return notes;
    }

    private static String joinPercents(JsonArray array) {
        List<String> values = new ArrayList<>();
        array.forEach(value -> values.add(percent(value.getAsDouble())));
        return String.join(" / ", values);
    }

    private static String percent(double value) { return String.format(Locale.ROOT, "%.2f%%", value * 100); }
    private static String humanName(String value) { return value.replace('/', ' ').replace('_', ' '); }
    private static int weight(JsonObject entry) { return entry.has("weight") ? entry.get("weight").getAsInt() : 1; }
    private static String number(JsonElement element, String fallback) {
        if (element == null) return fallback;
        if (element.isJsonPrimitive()) return element.getAsBigDecimal().stripTrailingZeros().toPlainString();
        JsonObject object = element.getAsJsonObject();
        if (object.has("min") && object.has("max")) return number(object.get("min"), "0") + "–" + number(object.get("max"), "0");
        if (object.has("value")) return number(object.get("value"), fallback);
        return element.toString();
    }
    private static JsonArray array(JsonObject object, String key) { return object.has(key) ? object.getAsJsonArray(key) : new JsonArray(); }
    private static String string(JsonObject object, String key, String fallback) { return object.has(key) ? object.get(key).getAsString() : fallback; }
    private static Component join(List<Component> components, String separator) {
        var result = Component.empty();
        for (Component component : components) {
            if (!result.getSiblings().isEmpty()) result.append(separator);
            result.append(component);
        }
        return result;
    }
    static Component text(String suffix, Object... args) { return Component.translatable("jei." + MOD + ".acquisition." + suffix, args); }

    public static List<AcquisitionRecipe> flames() {
        List<AcquisitionRecipe> out = new ArrayList<>();
        for (Item item : BuiltInRegistries.ITEM) {
            if (!(item instanceof FlameSeedItem seed)) continue;
            FlameKind kind = seed.kind();
            ItemStack vessel = new ItemStack(ModItems.FLAME_VESSEL.get());
            // Display identity is stable; acquisition never modifies an actual world entity.
            FlameVesselItem.fill(vessel, kind, new UUID(0, kind.modelIndex()));
            List<Component> notes = List.of(text("flame." + kind.name().toLowerCase(Locale.ROOT)), text("capture"), text("essence_not_item"));
            out.add(new AcquisitionRecipe(ResourceLocation.fromNamespaceAndPath(MOD, "acquisition/flame/" + kind.id()),
                    AcquisitionRecipe.Kind.FLAME, kind.displayName(), new ItemStack(item), vessel, notes, List.of(new ItemStack(item))));
        }
        return List.copyOf(out);
    }
}
