package com.example.immortal_cultivation_mod.localization;

import com.example.immortal_cultivation_mod.alchemy.AlchemyChemistry;
import com.example.immortal_cultivation_mod.attachment.BodyTypes;
import com.example.immortal_cultivation_mod.attachment.CultivationMethods;
import com.example.immortal_cultivation_mod.attachment.SpiritRoots;
import com.example.immortal_cultivation_mod.flame.FlameKind;
import com.example.immortal_cultivation_mod.guidance.DaoGuidanceContent;
import com.example.immortal_cultivation_mod.spell.ModSpells;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.contents.TranslatableContents;
import net.minecraft.world.item.ItemStack;
import net.neoforged.neoforge.gametest.GameTestHolder;
import net.neoforged.neoforge.gametest.PrefixGameTestTemplate;

/** Check actual registered content, including names generated by registry helpers. */
@GameTestHolder("immortal_cultivation_localization")
@PrefixGameTestTemplate(false)
public final class LocalizationGameTests {
    private static final String MOD = "immortal_cultivation_mod";

    private static JsonObject language(String locale) {
        var stream = LocalizationGameTests.class.getResourceAsStream("/assets/" + MOD + "/lang/" + locale + ".json");
        if (stream == null) throw new IllegalStateException("Missing packaged language: " + locale);
        try (var reader = new InputStreamReader(stream, StandardCharsets.UTF_8)) {
            return JsonParser.parseReader(reader).getAsJsonObject();
        } catch (java.io.IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private static void require(JsonObject lang, String key, List<String> missing) {
        if (!lang.has(key) || lang.get(key).getAsString().isBlank()) missing.add(key);
    }

    private static void require(JsonObject lang, Component component, List<String> missing) {
        if (component.getContents() instanceof TranslatableContents text) {
            require(lang, text.getKey(), missing);
            for (Object arg : text.getArgs()) if (arg instanceof Component child) require(lang, child, missing);
        }
        for (Component sibling : component.getSiblings()) require(lang, sibling, missing);
    }

    @GameTest(template = "fate_test")
    public static void registeredItemsBlocksEntitiesEffectsAndTabsHaveBothLanguages(GameTestHelper h) {
        List<String> missing = new ArrayList<>();
        for (String locale : List.of("en_us", "zh_cn")) {
            JsonObject lang = language(locale);
            List<String> localMissing = new ArrayList<>();
            BuiltInRegistries.ITEM.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDescriptionId(new ItemStack(e.getValue())), localMissing));
            BuiltInRegistries.BLOCK.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDescriptionId(), localMissing));
            BuiltInRegistries.ENTITY_TYPE.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDescriptionId(), localMissing));
            BuiltInRegistries.MOB_EFFECT.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDescriptionId(), localMissing));
            BuiltInRegistries.ATTRIBUTE.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDescriptionId(), localMissing));
            BuiltInRegistries.CREATIVE_MODE_TAB.entrySet().stream().filter(e -> e.getKey().location().getNamespace().equals(MOD))
                    .forEach(e -> require(lang, e.getValue().getDisplayName(), localMissing));
            missing.addAll(localMissing.stream().distinct().map(k -> locale + ": " + k).toList());
        }
        h.assertTrue(missing.isEmpty(), "Untranslated registered content: " + missing.size() + " missing: " + String.join(", ", missing.stream().limit(8).toList()));
        h.succeed();
    }

    @GameTest(template = "fate_test")
    public static void generatedCatalogAndGuidanceKeysHaveBothLanguages(GameTestHelper h) {
        List<String> missing = new ArrayList<>();
        for (String locale : List.of("en_us", "zh_cn")) {
            JsonObject lang = language(locale);
            List<String> localMissing = new ArrayList<>();
            for (var spell : ModSpells.all()) {
                require(lang, spell.name(), localMissing);
                require(lang, "spell." + MOD + "." + spell.translationKey() + ".description", localMissing);
            }
            for (var method : CultivationMethods.allMethods()) {
                require(lang, method.nameKey(), localMissing);
                require(lang, SpiritRoots.elementSpecDisplayName(method.element()), localMissing);
            }
            for (var root : SpiritRoots.ALL_ELEMENTS) require(lang, SpiritRoots.elementDisplayName(root), localMissing);
            for (var grade : SpiritRoots.GRADES) require(lang, SpiritRoots.gradeDisplayName(grade), localMissing);
            for (String key : List.of("root_details", "root_chart.five", "root_chart.special",
                    "root_chart.absent", "root_chart.explanation")) require(lang, "screen." + MOD + "." + key, localMissing);
            for (var body : BodyTypes.VALUES) {
                require(lang, BodyTypes.displayName(body), localMissing);
                require(lang, BodyTypes.description(body), localMissing);
                require(lang, BodyTypes.rarityName(body), localMissing);
            }
            for (int n = 0; n <= 5; n++) require(lang, "cultivation." + MOD + ".roots." + n, localMissing);
            require(lang, SpiritRoots.displayName(List.of("光", "暗", SpiritRoots.FIRE), SpiritRoots.GRADE_HEAVEN), localMissing);
            for (var flame : FlameKind.values()) {
                require(lang, flame.displayName(), localMissing);
                require(lang, flame.affinity(), localMissing);
                require(lang, flame.maxGrade(), localMissing);
            }
            for (var element : AlchemyChemistry.Element.values()) require(lang, "alchemy.element." + element.name(), localMissing);
            for (var effect : AlchemyChemistry.Effect.values()) require(lang, "alchemy.effect." + effect.name(), localMissing);
            for (var trait : AlchemyChemistry.Trait.values()) require(lang, "alchemy.trait." + trait.name(), localMissing);
            for (String plant : AlchemyChemistry.PLANTS.keySet()) require(lang, "alchemy.plant." + plant, localMissing);
            for (var chapter : DaoGuidanceContent.chapters()) {
                require(lang, DaoGuidanceContent.chapterKey(chapter.id(), "name"), localMissing);
                require(lang, DaoGuidanceContent.chapterKey(chapter.id(), "intro"), localMissing);
                for (var objective : chapter.objectives()) {
                    require(lang, DaoGuidanceContent.objectiveKey(chapter.id(), objective.id(), "name"), localMissing);
                    require(lang, DaoGuidanceContent.objectiveKey(chapter.id(), objective.id(), "detail"), localMissing);
                }
            }
            missing.addAll(localMissing.stream().distinct().map(k -> locale + ": " + k).toList());
        }
        h.assertTrue(missing.isEmpty(), "Untranslated catalog entries: " + missing.size() + " missing: " + String.join(", ", missing.stream().limit(8).toList()));
        h.succeed();
    }
}
