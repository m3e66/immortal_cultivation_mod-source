   public void clientTick(Level level, BlockPos pos, BlockState state) {
      Minecraft mc = Minecraft.getInstance();
      if (mc.level != null && mc.gameRenderer != null) {
         Frustum frustum = mc.levelRenderer.getFrustum();
         if (frustum != null) {
            AABB box = new AABB(pos).inflate(1.0);
            if (frustum.isVisible(box)) {
               if (level.getNearestPlayer((double)pos.getX() + 0.5, (double)pos.getY() + 0.5, (double)pos.getZ() + 0.5, 32.0, false) != null) {
                  if (level != null) {
                     double cx = (double)pos.getX() + 0.5;
                     double cy = (double)pos.getY() + 0.05;
                     double cz = (double)pos.getZ() + 0.5;
                  }
               }
            }
         }
      }
   }

   public static BlockPos findCenterBlock(Level level, BlockPos pos) {
      for (MagicCenterBlockEntity center : MagicCenterBlockEntity.getLoadedCentersNear(
            level, pos, SEARCH_RADIUS)) {
         BlockPos centerPos = center.getBlockPos();
         int dx = centerPos.getX() - pos.getX();
         int dy = centerPos.getY() - pos.getY();
         int dz = centerPos.getZ() - pos.getZ();
         double radius = center.getRadius() + 0.5D;
         if (Math.abs(dy) <= 1 && center.isBlank()
               && dx * dx + dz * dz <= radius * radius) {
            return centerPos;
         }
      }
      return null;
   }

   public BlockPos findOwningCenter() {
      if (level == null) {
         return null;
      }
      long gameTime = level.getGameTime();
      if (cachedCenterPos != null
            && level.getBlockEntity(cachedCenterPos) instanceof MagicCenterBlockEntity center
            && center.isBlank()
            && Vec3.atCenterOf(worldPosition).distanceToSqr(center.centerPoint())
            <= center.getRadius() * center.getRadius()) {
         return cachedCenterPos;
      }
      if (gameTime < nextCenterLookupTick) {
         return null;
      }
      nextCenterLookupTick = gameTime + 40L;
      cachedCenterPos = findCenterBlock(level, worldPosition);
      return cachedCenterPos;
   }

   private static int countSameTypeCircles(Level level, BlockPos centerPos, int radius, CircleType type) {
      int count = 0;

      for (int x = -radius; x <= radius; x++) {
         for (int z = -radius; z <= radius; z++) {
            double hDist = Math.sqrt((double)(x * x + z * z));
            if (!(hDist > (double)radius + 0.5)) {
               for (int y = -1; y <= 1; y++) {
                  BlockPos checkPos = centerPos.offset(x, y, z);
                  BlockState state = level.getBlockState(checkPos);
                  if (state.is((Block)ModBlocks.MAGIC_CIRCLE_BLOCK.get())
                     && state.getValue(MagicCircleBlock.CIRCLE_TYPE) == type
                     && !ComboBlockEntity.isCirclePartOfActiveCombo(level, checkPos)) {
                     count++;
                  }
               }
            }
         }
      }

      return count;
   }
